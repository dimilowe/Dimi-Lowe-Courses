export type IconKey = keyof typeof ICON_REGISTRY;

export function isIconKey(x: unknown): x is IconKey {
  return typeof x === "string" && x in ICON_REGISTRY;
}

export function getIconComponent(iconKey: unknown): LucideIcon {
  return isIconKey(iconKey) ? ICON_REGISTRY[iconKey] : ICON_REGISTRY.sparkles;
}
